def _rows():
    lines = [(1, i, t) for i, t in enumerate(_CF_3017_P9)]
    rows, _, _ = parse_statement_lines(lines, "cf", section_headers=SECTION_HEADERS["cf"])
    return rows


def test_cf_header_side_by_side_with_dot_ranges() -> None:  # C1
    h = detect_header(_CF_3017_P9)
    assert h.side_by_side is True
    assert h.periods == ["115-01-01~115-06-30", "114-01-01~114-06-30"]


def test_bs_side_by_side_detection_unchanged() -> None:  # C2
    h = detect_header([
        "合併資產負債表",
        "115.6.30 114.12.31 114.6.30 115.6.30 114.12.31 114.6.30",
        "資　　產 金　　額 % 金　　額 % 金　　額 % 　負債及權益 金　　額 % 金　　額 % 金　　額 %",
    ])
    assert h.side_by_side is True and h.periods == ["115-06-30", "114-12-31", "114-06-30"]


def test_non_side_by_side_cf_unchanged() -> None:  # C3
    h = detect_header(["合併現金流量表", "115年1月1日至6月30日 114年1月1日至6月30日", "代碼 項目 金額 金額"])
    assert h.side_by_side is False and h.n == 2


def test_right_half_split_by_bcde_codes() -> None:
    k = {r.key: r for r in _rows() if r.key}
    assert k["pretax_income_cf"].current == 25914090 and k["pretax_income_cf"].prior == 10516502
    assert k["cfo"].current == 26290591
    assert k["cfi"].current == -11639244 and k["cfi"].code == "BBBB"
    assert k["cff"].current == 2958385
    assert k["fx_effect"].current == 1574992
    assert k["net_change_in_cash"].current == 19184724
    assert k["capex"].current == -7111878 and "折舊" not in k["capex"].label


def test_right_only_row_and_left_a_code_rows_stay_on_their_side() -> None:
    rows = _rows()
    end = next(r for r in rows if r.code == "E00200")
    assert end.key == "cash_ending" and end.current == 77714522
    a32125 = next(r for r in rows if r.code == "A32125")
    assert a32125.section != "籌資活動之現金流量"
